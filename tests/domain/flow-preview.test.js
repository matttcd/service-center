import { describe, it, expect } from 'vitest'
import {
  TECHNICIAN, createDemoOrders, applyDemoAction, nextAction, queueOrders, receptionQueue, charges, workAge,
} from '../../src/preview/preview-model.js'

const fixture = (number) => createDemoOrders(1800000000000).find((order) => order.number === number)
const counter = (order, action, payload) => applyDemoAction(order, action, payload, 'recepcion')

describe('Vista previa del flujo: simulación aislada', () => {
  it.each([
    [0, 'recién'], [59000, 'recién'], [60000, 'hace 1 min'], [59 * 60000, 'hace 59 min'],
    [3600000, 'hace 1 h'], [2 * 3600000, 'hace 2 h'], [86400000, 'hace 1 d'], [-1000, 'recién'],
  ])('muestra el tiempo transcurrido de trabajo para %s ms', (elapsed, expected) => {
    expect(workAge({ assignedTo: TECHNICIAN, acceptedAt: 1800000000000 }, 1800000000000 + elapsed)).toBe(expected)
  })
  it('cuenta desde la aceptación y conserva el tiempo en presupuestos, repuestos y reanudaciones', () => {
    const now = 1800000000000
    let order = applyDemoAction(fixture('OS1047'), 'claim', {}, 'tecnico', now)
    expect(order.acceptedAt).toBe(now)
    expect(workAge(order, now)).toBe('recién')
    order = applyDemoAction(order, 'saveWork', { work: 'Cambiar módulo' }, 'tecnico', now + 3600000)
    order = applyDemoAction(order, 'sendQuote', {}, 'tecnico', now + 2 * 3600000)
    expect(workAge(order, now + 2 * 3600000)).toBe('hace 2 h')
    order = counter(order, 'price', { price: 65000 })
    order = counter(order, 'notify')
    order = counter(order, 'approve')
    order = applyDemoAction(order, 'startRepair', {}, 'tecnico', now + 3 * 3600000)
    expect(workAge(order, now + 3 * 3600000)).toBe('hace 3 h')
    order = applyDemoAction(order, 'requestPart', { name: 'Módulo', quantity: 1 })
    expect(workAge(order, now + 4 * 3600000)).toBe('hace 4 h')
    order = counter(order, 'partOrdered', { id: order.parts[0].id })
    order = counter(order, 'partArrived', { id: order.parts[0].id })
    order = applyDemoAction(order, 'resume', {}, 'tecnico', now + 5 * 3600000)
    expect(order.acceptedAt).toBe(now)
    expect(workAge(order, now + 5 * 3600000)).toBe('hace 5 h')
  })
  it('muestra tiempo en todos mis trabajos y ninguno en los equipos sin aceptar', () => {
    const now = 1800000000000
    for (const order of queueOrders(createDemoOrders(now), 'tecnico', 'mine')) expect(workAge(order, now)).toMatch(/^hace /)
    expect(workAge(fixture('OS1047'), now)).toBe('')
    expect(workAge({ assignedTo: TECHNICIAN, acceptedAt: null }, now)).toBe('')
  })
  it('permite reparar un cambio de módulo definido por recepción sin completar diagnóstico', () => {
    const original = fixture('OS1045')
    expect(original).not.toHaveProperty('diagnosis')
    expect(original.status).toBe('recibido')
    expect(original.workAuthor).toEqual({ name: 'Sofía', role: 'recepcion' })
    expect(original.history.at(-1)).toMatchObject({ work: original.work, by: 'Sofía · Recepción' })
    const started = applyDemoAction(original, 'startRepair')
    const finished = applyDemoAction(started, 'finish')
    expect(finished.status).toBe('terminado')
    expect(finished).not.toHaveProperty('diagnosis')
    expect(finished.workAuthor).toEqual(original.workAuthor)
  })
  it('conserva la autoría y la reparación definida si se guarda sin cambios', () => {
    const original = applyDemoAction(fixture('OS1045'), 'startRepair')
    const result = applyDemoAction(original, 'saveWork', { work: original.work })
    expect(result.status).toBe('en_reparacion')
    expect(result.workAuthor).toEqual(original.workAuthor)
    expect(result.work).toBe(original.work)
    expect(result.history.at(-1)).not.toHaveProperty('previousWork')
    expect(result).not.toHaveProperty('diagnosis')
  })
  it('devuelve a presupuesto un cambio de reparación y exige nuevo aviso y aprobación', () => {
    const original = { ...applyDemoAction(fixture('OS1045'), 'startRepair'), confirmed: true, notified: true, confirmedAt: 1, notifiedAt: 1 }
    expect(() => applyDemoAction(original, 'finish', { work: 'Reparar placa' })).toThrow(/Guardá/)
    let changed = applyDemoAction(original, 'saveWork', { work: 'Reparar placa' })
    expect(changed).toMatchObject({ status: 'presupuesto', confirmed: false, notified: false, confirmedAt: null, notifiedAt: null, price: original.price, advance: original.advance })
    expect(receptionQueue(changed)).toBe('avisar')
    expect(nextAction(changed, 'tecnico')).toBeNull()
    expect(() => applyDemoAction(changed, 'startRepair')).toThrow()
    changed = counter(changed, 'price', { price: 78000 })
    changed = counter(changed, 'notify')
    changed = counter(changed, 'approve')
    expect(applyDemoAction(changed, 'startRepair').status).toBe('en_reparacion')
  })
  it.each(['saveWork', 'sendQuote'])('registra antes, después, autor y fecha al cambiar el trabajo mediante %s', (action) => {
    const original = action === 'sendQuote' ? fixture('OS1042') : applyDemoAction(fixture('OS1045'), 'startRepair')
    const now = 1800000005000
    const result = applyDemoAction(original, action, { work: 'Cambiar módulo con marco y comprobar sensores.' }, 'tecnico', now)
    expect(result.workAuthor).toEqual({ name: 'Juan', role: 'tecnico' })
    expect(result.history.at(-1)).toMatchObject({ previousWork: original.work, work: result.work, by: 'Juan · Técnico', at: now })
    expect(result.issue).toBe(original.issue)
    expect(original.work).not.toBe(result.work)
    expect(original.history).not.toEqual(result.history)
  })
  it('toma e inicia el equipo sin modificar los datos de origen ni permitir otra toma', () => {
    const original = fixture('OS1047')
    const result = applyDemoAction(original, 'claim')
    expect(result.assignedTo).toBe(TECHNICIAN)
    expect(result.status).toBe('en_revision')
    expect(original.assignedTo).toBe(null)
    expect(original.status).toBe('recibido')
    expect(() => applyDemoAction(result, 'claim')).toThrow()
    expect(() => counter(original, 'claim')).toThrow()
  })
  it('recorre revisión, reparación propuesta, precio, aviso, aprobación y reparación entre roles', () => {
    let order = applyDemoAction(fixture('OS1047'), 'claim')
    expect(() => applyDemoAction(order, 'sendQuote')).toThrow(/Definí/)
    order = applyDemoAction(order, 'sendQuote', { work: 'Reemplazar batería' })
    expect(receptionQueue(order)).toBe('presupuestar')
    expect(nextAction(order, 'tecnico')).toBe(null)
    order = counter(order, 'price', { price: 45000 })
    expect(receptionQueue(order)).toBe('avisar')
    expect(() => counter(order, 'approve')).toThrow()
    order = counter(order, 'notify')
    expect(receptionQueue(order)).toBe('respuesta')
    order = counter(order, 'approve')
    order = applyDemoAction(order, 'startRepair')
    order = applyDemoAction(order, 'finish')
    expect(order.status).toBe('terminado')
    expect(order.work).toBe('Reemplazar batería')
    expect(receptionQueue(order)).toBe('avisar')
  })
  it('no entrega al rechazar y conserva presupuesto y seña con un importe de retiro cero', () => {
    const original = fixture('OS1035')
    const rejected = counter(original, 'reject', { charge: 0 })
    expect(rejected.status).toBe('presupuesto_rechazado')
    expect(rejected.price).toBe(original.price)
    expect(rejected.rejectedCharge).toBe(0)
    expect(receptionQueue(rejected)).toBe('retiros')
    expect(charges({ ...rejected, advance: 5000 })).toEqual({ total: 0, balance: -5000 })
    expect(nextAction(rejected, 'tecnico')).toBe(null)
    for (const charge of ['', -1, 'no', Infinity, undefined]) expect(() => counter(original, 'reject', { charge })).toThrow()
  })
  it('mantiene la espera hasta recibir todos los repuestos y retomar explícitamente', () => {
    let order = applyDemoAction(fixture('OS1044'), 'requestPart', { name: 'Módulo', quantity: 1 })
    order = applyDemoAction(order, 'requestPart', { name: 'Adhesivo', quantity: 1 })
    expect(nextAction(order, 'tecnico')).toBe(null)
    for (const part of order.parts) {
      expect(() => applyDemoAction(order, 'partOrdered', { id: part.id })).toThrow()
      order = counter(order, 'partOrdered', { id: part.id })
      order = counter(order, 'partArrived', { id: part.id })
    }
    expect(order.status).toBe('falta_repuestos')
    expect(nextAction(order, 'tecnico').id).toBe('resume')
    expect(applyDemoAction(order, 'resume').status).toBe('en_reparacion')
  })
  it('requiere el retiro físico y datos válidos para terceros', () => {
    const order = fixture('OS1020')
    expect(() => counter(order, 'pickup', { by: 'client' })).toThrow()
    expect(() => counter(order, 'pickup', { by: 'third', physical: true, name: 'Otra persona', dni: '1' })).toThrow()
    const delivered = counter(order, 'pickup', { by: 'third', physical: true, name: 'Otra persona', dni: '12345678' })
    expect(delivered.status).toBe('entregado')
    expect(charges(delivered)).toEqual({ total: 3500, balance: -1500 })
    expect(nextAction(delivered, 'recepcion')).toBe(null)
    expect(receptionQueue(delivered)).toBe(null)
  })
  it('impide al técnico editar otros trabajos o gestionar precios y respuestas', () => {
    expect(() => applyDemoAction(fixture('OS1040'), 'saveWork', { work: 'Cambio' })).toThrow()
    expect(() => applyDemoAction(fixture('OS1038'), 'price', { price: 100 })).toThrow()
    expect(() => applyDemoAction(fixture('OS1035'), 'approve')).toThrow()
    expect(() => counter(fixture('OS1042'), 'saveWork', { work: 'Cambio' })).toThrow()
  })
  it('prioriza trabajo disponible y no cambia la antigüedad al agregar notas', () => {
    const orders = createDemoOrders()
    const mine = queueOrders(orders, 'tecnico', 'mine')
    expect(mine[0].number).toBe('OS1031')
    const original = fixture('OS1042')
    const changed = applyDemoAction(original, 'note', { text: 'Comprobar con otro cargador' })
    expect(changed.statusSince).toBe(original.statusSince)
    expect(changed.notes).toHaveLength(1)
    expect(original.notes).toHaveLength(0)
    expect(queueOrders(orders, 'tecnico', 'all', 'A54')[0].number).toBe('OS1042')
  })
  it('crea un juego limpio al reiniciar sin compartir notas ni repuestos', () => {
    const first = createDemoOrders()
    first[0].notes.push({ text: 'Borrador' })
    expect(createDemoOrders()[0].notes).toHaveLength(0)
    const direct = fixture('OS1045')
    const edited = applyDemoAction(applyDemoAction(direct, 'startRepair'), 'saveWork', { work: 'Otro trabajo' })
    expect(edited.workAuthor.name).toBe('Juan')
    expect(fixture('OS1045').workAuthor.name).toBe('Sofía')
  })
})
