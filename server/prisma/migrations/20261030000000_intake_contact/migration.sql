-- Si ya existe la categoría correcta, conservar su fila y sumar ambos usos.
UPDATE "CatalogModel" target SET usage = target.usage + source.usage
FROM "CatalogModel" source, intake_catalog_types fix
WHERE source.brand = fix.brand AND source.name = fix.name AND source."deviceType" = fix.old_type
  AND target.brand = source.brand AND target.name = source.name AND target."deviceType" = fix.new_type;
DELETE FROM "CatalogModel" source USING intake_catalog_types fix
WHERE source.brand = fix.brand AND source.name = fix.name AND source."deviceType" = fix.old_type
  AND EXISTS (SELECT 1 FROM "CatalogModel" target WHERE target.brand = source.brand AND target.name = source.name AND target."deviceType" = fix.new_type);
UPDATE "CatalogModel" source SET "deviceType" = fix.new_type
FROM intake_catalog_types fix
WHERE source.brand = fix.brand AND source.name = fix.name AND source."deviceType" = fix.old_type;
DROP TABLE intake_catalog_types;
